func TestGeneratedDarwinLongDoubleResult(t *testing.T) {
	t.Run("Memmem", func(t *testing.T) {
		input := [8]nativeChar{'a', 'b', 'c', ':', 'd', 0}
		needle := [2]nativeChar{'b', 'c'}
		if c.Memmem(unsafe.Pointer(&input[0]), 5, unsafe.Pointer(&needle[0]), 2) != unsafe.Pointer(&input[1]) {
			t.Fatal("memmem match position differs")
		}
	})
	t.Run("SysNerr and SysErrlist", func(t *testing.T) {
		if c.SysNerr <= 0 {
			t.Fatalf("sys_nerr = %d", c.SysNerr)
		}
		errors := (**c.Char)(unsafe.Pointer(&c.SysErrlist))
		for i := c.Int(0); i < c.SysNerr; i++ {
			entry := c.Index(errors, i)
			if entry == nil {
				t.Fatalf("sys_errlist[%d] is nil", i)
			}
			if got, want := c.GoString(entry), c.GoString(c.Strerror(i)); got != want {
				t.Fatalf("sys_errlist[%d] = %q, strerror = %q", i, got, want)
			}
		}
	})
	t.Run("Suboptarg", func(t *testing.T) {
		previous := c.Suboptarg
		defer func() { c.Suboptarg = previous }()
		value := c.Str("llcppg suboption")
		c.Suboptarg = value
		if c.Suboptarg != value || c.GoString(c.Suboptarg) != "llcppg suboption" {
			t.Fatal("suboptarg storage differs")
		}
	})
	var end *c.Char
	value := c.Strtold(c.Str("1.5"), &end)
	if value != 1.5 || end == nil || *end != 0 {
		t.Fatalf("strtold value/end = %v/%p", value, end)
	}
}

